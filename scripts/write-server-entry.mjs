/**
 * Give the production build an entry file any Node host can start.
 *
 * ## Why this exists
 *
 * `vite build` already produces the whole production server: Nitro's
 * `node-server` bundle at `.output/server/index.mjs`, which serves the pages,
 * the server functions and the static assets from one process. What it does
 * not produce is a file every host will accept as an entry point:
 *
 * - some hosting panels (Hostinger's among them) insist on a `.js` extension;
 * - Passenger-style process managers start the entry with `require()`, which
 *   cannot load an ES module on every Node 22 release.
 *
 * So this writes `.output/server.js`: CommonJS (declared by the
 * `.output/package.json` written beside it, since the repository itself is
 * `"type": "module"`), loadable by `require()` and by `node` alike, and doing
 * nothing but hand over to the real bundle with a dynamic `import()`.
 *
 * It runs after `vite build` because Nitro empties `.output/` at the start of
 * every build — the entry is regenerated with the bundle it points at, and can
 * never outlive it.
 */

import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUTPUT = ".output";
const BUNDLE = "server/index.mjs";

if (!existsSync(join(OUTPUT, BUNDLE))) {
  console.error(`No ${OUTPUT}/${BUNDLE}. \`vite build\` did not produce a Node server bundle.`);
  process.exit(1);
}

/* Scoped to `.output/` alone: `.output/server/package.json`, which Nitro
   writes, still marks the bundle itself as an ES module. */
writeFileSync(
  join(OUTPUT, "package.json"),
  JSON.stringify({ private: true, type: "commonjs" }, null, 2) + "\n",
);

writeFileSync(
  join(OUTPUT, "server.js"),
  `// Generated by scripts/write-server-entry.mjs during \`npm run build\`. Do not edit.
//
// The production entry point: \`node .output/server.js\`. Loads the Nitro
// server bundle, which listens on PORT (or NITRO_PORT) on every interface
// unless HOST (or NITRO_HOST) says otherwise.
"use strict";

// The bundle was compiled for production; its dependencies should agree.
if (!process.env.NODE_ENV) process.env.NODE_ENV = "production";

import("./${BUNDLE}").catch((error) => {
  console.error("Oikonomia could not start:", error);
  process.exit(1);
});
`,
);

console.log(`Wrote ${OUTPUT}/server.js → ${OUTPUT}/${BUNDLE}`);
